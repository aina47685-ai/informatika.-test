// ==========================================
// ТЕСТТІ БАСТАУ
// ==========================================

function startTest() {

    studentName = document.getElementById("studentName").value.trim();

    if (studentName === "") {
        alert("Оқушының аты-жөнін енгізіңіз!");
        return;
    }

    currentVariant = Number(
        document.getElementById("variantSelect").value
    );

    currentQuestion = 0;
    score = 0;

    document.getElementById("start-screen")
        .classList.add("hidden");

    document.getElementById("test-screen")
        .classList.remove("hidden");

    document.getElementById("studentDisplay")
        .textContent = studentName;

    showQuestion();
}


// ==========================================
// СҰРАҚТЫ КӨРСЕТУ
// ==========================================

function showQuestion() {

    const questionData =
        variants[currentVariant][currentQuestion];

    document.getElementById("questionNumber")
        .textContent =
        `Сұрақ: ${currentQuestion + 1} / 10`;

    document.getElementById("question")
        .textContent =
        questionData.question;

    const answersDiv =
        document.getElementById("answers");

    answersDiv.innerHTML = "";

    selectedAnswer = null;

    questionData.answers.forEach((answer, index) => {

        const label = document.createElement("label");

        label.className = "answer";

        label.innerHTML = `
            <input
                type="radio"
                name="answer"
                value="${index}"
            >
            ${answer}
        `;

        label.querySelector("input")
            .addEventListener("change", function() {
                selectedAnswer = index;
            });

        answersDiv.appendChild(label);
    });

    const progress =
        ((currentQuestion + 1) / 10) * 100;

    document.getElementById("progressBar")
        .style.width = progress + "%";

    if (currentQuestion === 9) {

        document.getElementById("nextBtn")
            .textContent = "🏁 Тестті аяқтау";

    } else {

        document.getElementById("nextBtn")
            .textContent = "Келесі →";
    }
}


// ==========================================
// КЕЛЕСІ СҰРАҚ
// ==========================================

function nextQuestion() {

    if (selectedAnswer === null) {

        alert("Жауаптардың бірін таңдаңыз!");

        return;
    }

    const correctAnswer =
        variants[currentVariant][currentQuestion].correct;

    if (selectedAnswer === correctAnswer) {
        score++;
    }

    if (currentQuestion < 9) {

        currentQuestion++;

        showQuestion();

    } else {

        showResult();
    }
}


// ==========================================
// НӘТИЖЕНІ КӨРСЕТУ
// ==========================================

function showResult() {

    const wrong = 10 - score;

    const percent = score * 10;

    let grade;

    if (score >= 9) {
        grade = 5;
    } else if (score >= 7) {
        grade = 4;
    } else if (score >= 5) {
        grade = 3;
    } else {
        grade = 2;
    }

    document.getElementById("test-screen")
        .classList.add("hidden");

    document.getElementById("result-screen")
        .classList.remove("hidden");

    document.getElementById("resultName")
        .textContent =
        `Оқушы: ${studentName}`;

    document.getElementById("correct")
        .textContent = score;

    document.getElementById("wrong")
        .textContent = wrong;

    document.getElementById("percent")
        .textContent = percent;

    document.getElementById("grade")
        .textContent = grade;
}


// ==========================================
// ҚАЙТА БАСТАУ
// ==========================================

function restartTest() {

    currentQuestion = 0;
    score = 0;

    document.getElementById("result-screen")
        .classList.add("hidden");

    document.getElementById("start-screen")
        .classList.remove("hidden");

    document.getElementById("studentName")
        .value = "";
}